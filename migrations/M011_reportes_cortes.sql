CREATE TABLE IF NOT EXISTS reportes_cortes (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tipo_reporte VARCHAR(40) NOT NULL DEFAULT 'FINANCIERO_E2',
  version VARCHAR(20) NOT NULL DEFAULT 'E2',
  periodo_desde DATE NOT NULL,
  periodo_hasta DATE NOT NULL,
  capturado_en DATETIME NOT NULL,
  filtros_json JSON NULL,
  resumen_json JSON NOT NULL,
  controles_json JSON NULL,
  alertas_json JSON NULL,
  generado_por_id INT NULL,
  generado_por_nombre VARCHAR(120) NULL,
  estado ENUM('GENERADO','INVALIDADO') NOT NULL DEFAULT 'GENERADO',
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expira_en DATETIME NULL,
  KEY idx_reportes_cortes_periodo (periodo_desde, periodo_hasta),
  KEY idx_reportes_cortes_creado (creado_en)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS reportes_cortes_documentos (
  id INT AUTO_INCREMENT PRIMARY KEY,
  corte_id CHAR(36) NOT NULL,
  venta_id INT NOT NULL,
  numero_factura VARCHAR(50) NULL,
  fecha_comercial DATE NULL,
  fecha_fiscal DATE NULL,
  tipo_doc VARCHAR(45) NULL,
  tipo_f VARCHAR(1) NULL,
  estado_venta VARCHAR(45) NULL,
  segmento ENUM('normal','flete','pendiente') NOT NULL,
  signo SMALLINT NOT NULL DEFAULT 1,
  subtotal DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  iva_total DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  exento DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  total DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  total_firmado DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  neto_lineas DECIMAL(15,2) NULL,
  iva_lineas DECIMAL(15,2) NULL,
  diferencia_lineas DECIMAL(15,2) NULL,
  cliente_id INT NULL,
  cliente_nombre VARCHAR(255) NULL,
  cliente_cuit VARCHAR(45) NULL,
  cliente_condicion VARCHAR(100) NULL,
  cliente_ciudad VARCHAR(100) NULL,
  cliente_provincia VARCHAR(100) NULL,
  vendedor_emisor_id INT NULL,
  vendedor_emisor_nombre VARCHAR(120) NULL,
  vendedor_atribuible_id INT NULL,
  vendedor_nombre VARCHAR(120) NULL,
  vendedor_atribuible_origen ENUM('propio','referencia','asignacion_explicita','sin_atribucion') NULL,
  cuenta_id INT NULL,
  venta_referencia_id INT NULL,
  cae_id VARCHAR(20) NULL,
  estado_fiscal ENUM('NO_APLICA','SIN_SOLICITUD','EN_CURSO','RECHAZADO','DESCONOCIDO','AUTORIZADO') NULL,
  estado_conciliacion ENUM('NO_EVALUADO','CONCILIADO','DISCREPANTE','EVIDENCIA_INCOMPLETA','CONFLICTO') NOT NULL DEFAULT 'NO_EVALUADO',
  alertas_json JSON NULL,
  creado_en DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_reportes_cortes_documento (corte_id, venta_id),
  KEY idx_reportes_cortes_doc_venta (venta_id),
  KEY idx_reportes_cortes_doc_fecha_fiscal (fecha_fiscal),
  KEY idx_reportes_cortes_doc_vendedor (vendedor_atribuible_id),
  CONSTRAINT FK_reportes_cortes_documentos_corte FOREIGN KEY (corte_id) REFERENCES reportes_cortes(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
